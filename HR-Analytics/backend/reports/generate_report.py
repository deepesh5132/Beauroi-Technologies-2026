"""
PDF Executive Report Generation Module using ReportLab.
Generates printable, beautiful enterprise HR Analytics PDF reports.
"""

import os
import io
from typing import Dict, Any, List
import pandas as pd

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable

def generate_pdf_report_bytes(
    kpis: Dict[str, Any],
    dept_data: List[Dict[str, Any]],
    report_title: str = "Executive HR Workforce Attrition & Analytics Audit Report"
) -> bytes:
    """Generate PDF document bytes for HTTP streaming or direct file download."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    
    styles = getSampleStyleSheet()
    
    # Custom Brand Palette
    NAVY = colors.HexColor("#0F172A")
    TEAL = colors.HexColor("#0D9488")
    TEXT_DARK = colors.HexColor("#334155")
    BG_LIGHT = colors.HexColor("#F8FAFC")
    ACCENT_RED = colors.HexColor("#EF4444")
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        leading=24,
        textColor=NAVY,
        spaceAfter=6
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=TEAL,
        spaceAfter=15
    )
    
    section_style = ParagraphStyle(
        'SectionHeader',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=NAVY,
        spaceBefore=12,
        spaceAfter=8
    )
    
    body_style = ParagraphStyle(
        'BodyTextCustom',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9.5,
        leading=14,
        textColor=TEXT_DARK
    )
    
    elements = []
    
    # 1. Header Banner
    elements.append(Paragraph(report_title, title_style))
    elements.append(Paragraph("Generated by Internship Project beau roi Platform • Confidential", subtitle_style))
    elements.append(HRFlowable(width="100%", thickness=2, color=TEAL, spaceBefore=0, spaceAfter=15))
    
    # 2. Executive Summary KPIs Table
    elements.append(Paragraph("1. Executive Workforce Metrics", section_style))
    
    kpi_table_data = [
        [
            Paragraph("<b>Metric</b>", body_style),
            Paragraph("<b>Value</b>", body_style),
            Paragraph("<b>Metric</b>", body_style),
            Paragraph("<b>Value</b>", body_style)
        ],
        [
            Paragraph("Total Employees", body_style),
            Paragraph(f"{kpis.get('total_employees', 0):,}", body_style),
            Paragraph("Active Headcount", body_style),
            Paragraph(f"{kpis.get('active_employees', 0):,}", body_style)
        ],
        [
            Paragraph("Attrition Rate", body_style),
            Paragraph(f"<b>{kpis.get('attrition_rate', 0.0)}%</b>", body_style),
            Paragraph("Average Monthly Income", body_style),
            Paragraph(f"${kpis.get('avg_salary', 0.0):,.2f}", body_style)
        ],
        [
            Paragraph("Average Age", body_style),
            Paragraph(f"{kpis.get('avg_age', 0.0)} Years", body_style),
            Paragraph("Average Tenure", body_style),
            Paragraph(f"{kpis.get('avg_tenure', 0.0)} Years", body_style)
        ],
        [
            Paragraph("Overtime Ratio", body_style),
            Paragraph(f"{kpis.get('overtime_pct', 0.0)}%", body_style),
            Paragraph("Highest Attrition Department", body_style),
            Paragraph(f"<b>{kpis.get('highest_risk_department', 'N/A')}</b>", body_style)
        ]
    ]
    
    t_kpis = Table(kpi_table_data, colWidths=[130, 120, 140, 130])
    t_kpis.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#E2E8F0")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('ALIGN', (1, 0), (1, -1), 'CENTER'),
        ('ALIGN', (3, 0), (3, -1), 'CENTER'),
        ('PADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(t_kpis)
    elements.append(Spacer(1, 15))
    
    # 3. Departmental Attrition Breakdown Table
    elements.append(Paragraph("2. Departmental Attrition Breakdown", section_style))
    
    dept_table_rows = [
        [
            Paragraph("<b>Department</b>", body_style),
            Paragraph("<b>Headcount</b>", body_style),
            Paragraph("<b>Attrition Count</b>", body_style),
            Paragraph("<b>Attrition %</b>", body_style),
            Paragraph("<b>Avg Monthly Income</b>", body_style)
        ]
    ]
    
    for row in dept_data:
        dept_table_rows.append([
            Paragraph(row.get("Department", row.get("department", "N/A")), body_style),
            Paragraph(str(row.get("total", 0)), body_style),
            Paragraph(str(row.get("attrition_count", 0)), body_style),
            Paragraph(f"{row.get('attrition_rate', 0.0)}%", body_style),
            Paragraph(f"${row.get('avg_salary', 0.0):,.2f}", body_style)
        ])
        
    t_dept = Table(dept_table_rows, colWidths=[150, 85, 95, 85, 105])
    t_dept.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#0F172A")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, BG_LIGHT]),
        ('PADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(t_dept)
    elements.append(Spacer(1, 15))
    
    # 4. Strategic Recommendations
    elements.append(Paragraph("3. Strategic HR Recommendations & Risk Mitigations", section_style))
    
    recs = [
        "<b>1. Overtime Compensation & Work-Life Balance:</b> Implement strict overtime monitoring for teams logging > 25% overtime. Overtime is identified as the #1 predictive feature for employee turnover.",
        "<b>2. Promotion Pathways & Fast-Tracking:</b> Establish bi-annual career growth audits for mid-level employees with > 4 years since their last promotion.",
        "<b>3. Targeted Compensation Adjustment:</b> Review compensation benchmarks for roles under $4,000/month in Sales and R&D to align with industry standard percentile targets.",
        "<b>4. Hybrid Work & Commute Flexibility:</b> Offer flexible hybrid remote schedules for employees commuting > 20 km to reduce burnout risk."
    ]
    
    for rec in recs:
        elements.append(Paragraph(f"• {rec}", body_style))
        elements.append(Spacer(1, 4))
        
    elements.append(Spacer(1, 15))
    elements.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#CBD5E1"), spaceBefore=10, spaceAfter=10))
    elements.append(Paragraph("Report Generated Automatically by HR Workforce Analytics AI Platform", ParagraphStyle('Footer', parent=styles['Normal'], fontSize=8, textColor=colors.HexColor("#94A3B8"), alignment=1)))
    
    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
